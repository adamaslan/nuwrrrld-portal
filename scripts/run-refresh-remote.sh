#!/usr/bin/env bash
#
# run-refresh-remote — portable remote wrapper around refresh-free-models.mjs.
#
# The bare script only rewrites a local checkout of lib/openrouter.ts, which is
# useless on an ephemeral cloud worker. This wrapper makes the refresh durable:
# it clones the repo, runs the refresh, and — only if the chain actually
# changed — pushes a branch and opens/updates a PR. Idempotent by design:
# no change => no commit, no PR, clean exit 0.
#
# Runs unchanged on GCP Cloud Run, Modal, or a Zo automation. Needs only bash,
# git, gh (or a plain git push), and Node 18+.
#
# Required env:
#   OPENROUTER_API_KEY   passed to the probe
#   GH_TOKEN             GitHub PAT (repo scope) for clone + push + PR
# Optional env:
#   REPO                 default: adamaslan/nuwrrrld-portal
#   BASE_BRANCH          default: main
#   PR_BRANCH            default: chore/refresh-free-models
#   MODEL_CHAIN_SIZE     forwarded to the refresh script (default 4)
#   OPEN_PR              "1" (default) opens/updates a PR; "0" pushes to BASE_BRANCH directly
#
# Exit codes: 0 = success (changed or not), 1 = refresh unsafe / hard error,
#             5 = DRIFT: GHA chain PR is open and this run's chain differs from it.
set -euo pipefail

REPO="${REPO:-adamaslan/nuwrrrld-portal}"
BASE_BRANCH="${BASE_BRANCH:-main}"
PR_BRANCH="${PR_BRANCH:-chore/refresh-free-models}"
ALERT_ASSIGNEE="${ALERT_ASSIGNEE:-adamaslan}"  # GitHub login to notify on drift
OPEN_PR="${OPEN_PR:-1}"

: "${OPENROUTER_API_KEY:?OPENROUTER_API_KEY is required}"
: "${GH_TOKEN:?GH_TOKEN (GitHub PAT, repo scope) is required}"

workdir="$(mktemp -d)"
trap 'rm -rf "$workdir"' EXIT

echo "==> Cloning $REPO@$BASE_BRANCH"
git clone --depth 1 --branch "$BASE_BRANCH" \
  "https://x-access-token:${GH_TOKEN}@github.com/${REPO}.git" "$workdir/repo"
cd "$workdir/repo"

git config user.name  "free-model-bot"
git config user.email "free-model-bot@users.noreply.github.com"

echo "==> Refreshing FREE_MODEL_CHAIN"
# The refresh script exits 1 on an unsafe result and leaves the file untouched;
# `set -e` propagates that so the job is marked failed without pushing garbage.
node scripts/refresh-free-models.mjs

# GitHub Actions is the scheduler of record. If its chain PR is open, this run
# must agree with it. Otherwise it alerts (exit 5) rather than writing a second
# chain, and the failed job is the alert. Matching by writing is not done here,
# because GHA holds no GCP credentials to trigger this job.
# Drift alert: one open GitHub issue assigned to the owner. GitHub emails
# assignees and sends a notification, so this reaches a person without a
# separate mail service. An existing open issue gets a comment, not a duplicate.
alert_drift() {
  local pr="$1" gha="$2" gcp="$3"
  local title="Free-model chain drift: GCP job disagrees with GHA PR #$pr"
  local body
  body="$(printf 'GHA chain PR #%s is open, but this GCP job selected a different chain.\n\nGHA chain:\n%s\n\nGCP chain:\n%s\n\nNothing was pushed. Decide which chain is right, then close this issue.' "$pr" "$gha" "$gcp")"
  local existing
  existing="$(gh issue list --repo "$REPO" --state open --search "in:title \"Free-model chain drift\"" --json number --jq '.[0].number // empty' 2>/dev/null || true)"
  if [[ -n "$existing" ]]; then
    gh issue comment "$existing" --repo "$REPO" --body "$body" >/dev/null || echo "could not comment on issue #$existing" >&2
  else
    gh issue create --repo "$REPO" --title "$title" --body "$body" \
      --label pipeline-failure --assignee "$ALERT_ASSIGNEE" >/dev/null \
      || echo "could not open drift issue" >&2
  fi
}

chain_of() {
  awk '/export const FREE_MODEL_CHAIN = \[/{f=1;next} /\] as const;/{f=0} f' | tr -d " ',\t"
}
gha_pr="$(gh pr list --repo "$REPO" --head "$PR_BRANCH" --state open --json number --jq '.[0].number // empty' 2>/dev/null || true)"
if [[ -n "$gha_pr" ]]; then
  git fetch -q origin "$PR_BRANCH"
  gha_chain="$(git show FETCH_HEAD:lib/openrouter.ts | chain_of)"
  gcp_chain="$(chain_of < lib/openrouter.ts)"
  if [[ "$gha_chain" == "$gcp_chain" ]]; then
    echo "==> GCP chain matches GHA PR #$gha_pr. Nothing to push."
    exit 0
  fi
  echo "DRIFT: GCP chain differs from GHA PR #$gha_pr." >&2
  echo "GHA chain:" >&2; echo "$gha_chain" >&2
  echo "GCP chain:" >&2; echo "$gcp_chain" >&2
  alert_drift "$gha_pr" "$gha_chain" "$gcp_chain"
  exit 5
fi

if git diff --quiet -- lib/openrouter.ts; then
  echo "==> No change — chain already current. Nothing to push."
  exit 0
fi

echo "==> Chain changed:"
git --no-pager diff -- lib/openrouter.ts

commit_msg="chore: refresh FREE_MODEL_CHAIN (automated)

Regenerated by refresh-free-models.mjs — probed OpenRouter's live \$0/:free
catalog and kept the reachable models in preference order.
"

if [[ "$OPEN_PR" == "0" ]]; then
  echo "==> Pushing directly to $BASE_BRANCH"
  git commit -am "$commit_msg"
  git push origin "HEAD:${BASE_BRANCH}"
  exit 0
fi

echo "==> Opening/updating PR on branch $PR_BRANCH"
git checkout -B "$PR_BRANCH"
git commit -am "$commit_msg"
# Plain push, never force. A non-fast-forward rejection means another writer
# (GitHub Actions, or a second copy of this script) already moved the branch.
# Overwriting it could replace a good chain with this run's, so fail loudly.
if ! git push origin "$PR_BRANCH"; then
  echo "==> Push to $PR_BRANCH was rejected (branch moved). Not forcing; resolve the branch by hand." >&2
  exit 1
fi

if command -v gh >/dev/null 2>&1; then
  # `gh pr view` returns exit 0 even for a closed/merged PR on this branch,
  # which would wrongly skip `gh pr create` on the next run after a merge.
  # Only an *open* PR should be treated as "already exists".
  open_pr="$(gh pr list --repo "$REPO" --head "$PR_BRANCH" --state open --json number --jq '.[0].number // empty' 2>/dev/null || true)"
  if [[ -n "$open_pr" ]] && [[ "$open_pr" != "null" ]]; then
    echo "==> PR #$open_pr already open for $PR_BRANCH — push updated it."
  else
    gh pr create --repo "$REPO" \
      --base "$BASE_BRANCH" --head "$PR_BRANCH" \
      --title "chore: refresh FREE_MODEL_CHAIN (automated)" \
      --body "Automated weekly refresh of the free-tier model fallback chain. See scripts/refresh-free-models.mjs."
  fi
else
  echo "==> gh not available; branch $PR_BRANCH pushed. Open the PR manually or set OPEN_PR=0."
fi
